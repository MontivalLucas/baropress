/// Deny by default: new commands require an explicit access decision.
pub fn allows(role: &str, command: &str) -> bool {
    if !["admin", "professional", "assistant"].contains(&role) {
        return false;
    }
    match command {
        "auth_change_password"
        | "auth_provision_recovery"
        | "app_settings_get"
        | "app_settings_save"
        | "patients_list"
        | "patients_get"
        | "patients_create"
        | "patients_update"
        | "patients_exam_history"
        | "exams_list"
        | "exams_get"
        | "exams_sequence"
        | "exams_raw_frames"
        | "appointments_list"
        | "appointments_save"
        | "professionals_list" => true,
        "dashboard_stats"
        | "appointments_delete"
        | "professionals_create"
        | "questionnaires_list"
        | "questionnaires_answer"
        | "questionnaires_history"
        | "exams_create"
        | "exams_create_sequence"
        | "exams_update_notes"
        | "exams_add_region"
        | "clinical_profiles"
        | "acquisition_connect"
        | "acquisition_disconnect"
        | "acquisition_start"
        | "acquisition_stop"
        | "acquisition_get_status" => role != "assistant",
        "auth_register_user"
        | "users_list"
        | "users_update"
        | "users_delete"
        | "users_recovery"
        | "patients_archive"
        | "exams_delete"
        | "questionnaires_save"
        | "backups_export"
        | "backups_preview"
        | "backups_import"
        | "system_logs_add"
        | "system_logs_list"
        | "acquisition_list_ports"
        | "calibration_list"
        | "calibration_save_mat"
        | "calibration_begin"
        | "calibration_append"
        | "calibration_finish"
        | "calibration_review"
        | "calibration_reclassify"
        | "calibration_frames"
        | "calibration_fit"
        | "calibration_validate"
        | "calibration_activate"
        | "calibration_deactivate"
        | "calibration_import" => role == "admin",
        _ => false,
    }
}
